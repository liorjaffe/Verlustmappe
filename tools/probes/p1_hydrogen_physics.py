def _u_vol_contribution(p_start, p_end):
    uV = R.entry("stor.volume_L")["uncertainty"]
    full = h2_from_tank_pressure(p_start, p_end)["uncertainty_rel"]
    R.REGISTRY["stor.volume_L"]["uncertainty"] = 0.0
    try:
        base = h2_from_tank_pressure(p_start, p_end)["uncertainty_rel"]
    finally:
        R.REGISTRY["stor.volume_L"]["uncertainty"] = uV
    return float(np.sqrt(max(full**2 - base**2, 0.0))), uV

contrib, uV = _u_vol_contribution(50, 150)
check("Errors COMMON to both readings (volume, common temperature offset) are wrongly amplified by p/dp",
      abs(contrib - uV) > 1e-6,
      "route2_tank_pv.py: a common factor enters the mass difference 1:1; only independent per-reading errors get the p/dp factor",
      f"volume contribution to u: {contrib:.4f}; physically correct (1:1): {uV:.4f}")

rows = []
for a, b in ((21.01325, 201.01325), (101.01325, 201.01325), (151.01325, 201.01325)):
    for dT in (15, 40, 64):
        true = temperature_corrected_mass(b, 800, 20+dT) - temperature_corrected_mass(a, 800, 20)
        assumed = temperature_corrected_mass(b, 800, 20) - temperature_corrected_mass(a, 800, 20)
        br = isothermal_adiabatic_bracket(a, b, 800, 20, dT)["relative_spread"]
        rows.append((a, b, dT, assumed/true-1, br))
check("The temperature 'bracket' (both endpoints +dT) understates a hot-end fill",
      all(bias > br for *_, bias, br in rows),
      "temperature_model.isothermal_adiabatic_bracket: model a hot END with an AMBIENT start (dT only at the end of a fill) and rename it",
      "\n    " + "\n    ".join(f"{a-1.01325:.0f}->{b-1.01325:.0f} barg dT={dT} K: real bias {bias*100:5.1f}%  bracket {br*100:4.1f}%"
                               for a, b, dT, bias, br in rows))

neg = AirDrivenBooster().account(10000, 35, 200, p_tank_start_barg=0, p_tank_end_barg=20)
check("Booster returns NEGATIVE compression energy when the tank stays below suction pressure",
      neg["energy_kWh"] < 0,
      "booster.py + isothermal_work_mol_integral: no work below suction pressure - integrate G(p) only for p >= p_suction, return 0 if p2 <= ps",
      f"tank 0->20 barg with EL at 35 barg: {neg['energy_kWh']:.1f} kWh")
ps = 36.01325; pg = np.linspace(1.01325, 201.01325, 200001)
w_code = isothermal_work_mol_integral(1000, 1.01325, 201.01325, 293.15, p_suction_abs_bar=ps)
w_ok = 1000*8.314462618*293.15*np.trapezoid(np.log(np.maximum(pg, ps)/ps), pg)/200.0/3.6e6
check("Fill integral counts negative work below suction (0->200 barg fill ~17% too low)",
      w_code < w_ok,
      "same fix as above",
      f"code {w_code:.3f} kWh vs clipped {w_ok:.3f} kWh")

